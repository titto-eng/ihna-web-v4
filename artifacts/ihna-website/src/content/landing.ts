// Registry of the hardcoded landing pages (60-landing). Hand-edited constants; no CMS global behind it. Keep it plain data.
// One row per landing route file (IHNA: /study-at-ihna/..., /healthcare-courses-*/, /walkin-enquiry/, /walkin-registration/, /lp/...). The thank-you,
// campaign and enquiry pipeline read it. `course` and `campus` are lookup slugs in the CMS; `courseCode`/`khId`/`campusKey` are the
// CRM keys (src/content/course-crm.ts) the destinations use when the form has no picker. `noindex: false` is the only way a landing
// page enters the sitemap.
export type LandingEntry = {
  path: string
  section: 'lp' | 'enquirenow' | 'study-at-ihna' | 'healthcare-courses' | 'walkin'
  slug: string
  title: string
  template: 'CourseLanding' | 'CampusBachelor' | 'CampusMaster' | 'EnquiryPage' | 'EventInvite' | 'NursingCity' | 'Regional' | 'WalkIn'
  formKey: string
  /** Thank-you URL (the old handler, GTM counts conversions on it); null = the form answers inline on the page. */
  thankYouPath: string | null
  course: string | null
  campus: string | null
  noindex: boolean
  /** Portal course id behind /lp/<slug>/application_form.php (DEC-55). */
  applicationCourseId?: number
  metaTitle?: string
  description?: string
  canonical?: string
  /** Other URLs that render this page (`.htaccess` aliases), each with its own route file. */
  aliases?: string[]
  courseCode?: string
  khId?: number
  campusKey?: string
  studentType?: 'domestic' | 'international'
  /** Campaign table code when the visitor brings none (41); IHNA landing pages use `lp_default`. */
  campaignFallback?: string
  /** A code the page always uses (staff data-entry pages such as `tollfree`). */
  fixedCampaign?: string
  /** HubSpot `campaign_source` the old page hard-coded (e.g. "IHNA Online Google Ad"). */
  hubspotCampaignSource?: string
  /** Show only these fields of the form (the form definition keeps the superset; the server validates against it). */
  formFields?: string[]
  /** Narrow a select field's options on this page (values of the form's own options). */
  fieldOptions?: Record<string, string[]>
  /** Funding line shown beside the course facts (e.g. "VET Student Loan"). */
  funding?: string
  /** `/study-at-ihna/<page>/<campaign>/` suffix URLs render the page (only where the old `.htaccess` rule works). */
  campaignSuffix?: boolean
}

